create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  description text,
  completed boolean not null default false
);
alter table public.tasks enable row level security;
grant usage on schema public to anon;
grant select, insert, update, delete on public.tasks to anon;
drop policy if exists "Public demo tasks select" on public.tasks;
drop policy if exists "Public demo tasks insert" on public.tasks;
drop policy if exists "Public demo tasks update" on public.tasks;
drop policy if exists "Public demo tasks delete" on public.tasks;
create policy "Public demo tasks select" on public.tasks for select to anon using (true);
create policy "Public demo tasks insert" on public.tasks for insert to anon with check (true);
create policy "Public demo tasks update" on public.tasks for update to anon using (true) with check (true);
create policy "Public demo tasks delete" on public.tasks for delete to anon using (true);
